function New-ZabbixTemplateCatalog {
    param([object[]]$Exports)
    $catalog = New-ZabbixMap
    foreach ($export in $Exports) {
        foreach ($template in $export.Data['templates']) {
            if ($template -isnot [System.Collections.IDictionary] -or $template['template'] -isnot [string] -or -not $template['template'].Trim()) {
                throw "Invalid template identity in '$($export.Path)'."
            }
            $key = "$($export.Version)|$($template['template'])"
            if ($catalog.ContainsKey($key)) {
                $a = ConvertTo-Json -InputObject $catalog[$key].Template -Depth 100 -Compress
                $b = ConvertTo-Json -InputObject $template -Depth 100 -Compress
                if ($a -cne $b) { throw "Ambiguous local template '$key': supply one export version/configuration for each identity." }
            }
            else { $catalog.Add($key, [PSCustomObject]@{ Template = $template; Export = $export }) }
        }
    }
    return ,$catalog
}

function Resolve-ZabbixTemplate {
    param($Catalog, [string]$Version, [string]$Name, [string[]]$Stack = @())
    $key = "$Version|$Name"
    if ($key -cin $Stack) { throw "Linked-template cycle: $(($Stack + $key) -join ' -> ')." }
    if ($Stack.Count -ge 32) { throw 'Linked-template depth exceeds 32.' }
    if (-not $Catalog.ContainsKey($key)) { throw "Missing local linked template '$key'." }
    $entry = $Catalog[$key]
    $merged = ConvertTo-ZabbixData $entry.Template
    $lineage = [System.Collections.Generic.List[string]]::new()
    $issues = [System.Collections.Generic.List[string]]::new()
    $sources = [System.Collections.Generic.List[object]]::new()
    $parents = [System.Collections.Generic.List[object]]::new()
    $globalExports = New-ZabbixMap
    foreach ($link in @($entry.Template['templates'])) {
        if ($null -eq $link -or $link -ceq '') { continue }
        if ($link -isnot [System.Collections.IDictionary] -or -not $link['name']) { throw "Invalid linked-template reference in '$key'." }
        $parentName = [string]$link['name']
        if (-not $Catalog.ContainsKey("$Version|$parentName")) {
            $issues.Add("Missing local linked template '$Version|$parentName'.")
            continue
        }
        $resolved = Resolve-ZabbixTemplate $Catalog $Version $parentName ($Stack + $key)
        $parents.Add($resolved.Template)
        foreach ($ancestor in $resolved.Lineage) { if (-not $lineage.Contains($ancestor)) { $lineage.Add($ancestor) } }
        foreach ($issue in $resolved.Issues) { $issues.Add($issue) }
        foreach ($source in $resolved.Sources) { $sources.Add($source) }
        foreach ($source in $resolved.GlobalExports) { $globalExports["$($source.Version)|$($source.Path)"] = $source }
    }
    foreach ($collection in @('items', 'discovery_rules', 'macros', 'triggers', 'graphs', 'valuemaps', 'dashboards')) {
        $combined = New-ZabbixMap
        foreach ($parent in $parents) {
            foreach ($item in @($parent[$collection])) {
                if ($null -eq $item -or $item -ceq '') { continue }
                if ($item -isnot [System.Collections.IDictionary]) { throw "Invalid $collection entry in '$key'." }
                $id = Get-ZabbixMergeIdentity $item $collection
                if ($combined.ContainsKey($id)) {
                    $a = ConvertTo-Json -InputObject $combined[$id] -Depth 100 -Compress
                    $b = ConvertTo-Json -InputObject $item -Depth 100 -Compress
                    if ($a -cne $b) { throw "Conflicting inherited $collection '$id' in '$key'." }
                }
                else { $combined.Add($id, $item) }
            }
        }
        $localSeen = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
        foreach ($item in @($entry.Template[$collection])) {
            if ($null -eq $item -or $item -ceq '') { continue }
            if ($item -isnot [System.Collections.IDictionary]) { throw "Invalid $collection entry in '$key'." }
            $id = Get-ZabbixMergeIdentity $item $collection
            if (-not $localSeen.Add($id)) { throw "Duplicate local $collection '$id' in '$key'." }
            $combined[$id] = ConvertTo-ZabbixData $item
        }
        if ($combined.Count -gt 0 -or $merged.ContainsKey($collection)) { $merged[$collection] = @($combined.Values) }
    }
    $merged.Remove('templates') | Out-Null
    if (-not $lineage.Contains($Name)) { $lineage.Add($Name) }
    $sources.Add([PSCustomObject]@{ Path = $entry.Export.Path; Sha256 = $entry.Export.Sha256; Version = $Version })
    $globalExports["$($entry.Export.Version)|$($entry.Export.Path)"] = $entry.Export
    [PSCustomObject]@{ Template = $merged; Lineage = $lineage.ToArray(); Issues = $issues.ToArray(); Sources = $sources.ToArray(); GlobalExports = @($globalExports.Values) }
}

function Get-ZabbixMergeIdentity {
    param($Item, [string]$Collection)
    $field = switch ($Collection) {
        'macros' { 'macro' } 'items' { 'key' } 'discovery_rules' { 'key' }
        'triggers' { 'expression' } default { 'name' }
    }
    if (-not $Item[$field]) {
        return '<invalid>-' + (Get-ZabbixDefinitionId (ConvertTo-Json -InputObject $Item -Depth 100 -Compress))
    }
    return [string]$Item[$field]
}

function Get-ZabbixMacroValues {
    param($Template, [System.Collections.IDictionary]$Overrides)
    $values = New-ZabbixMap
    foreach ($macro in @($Template['macros'])) {
        if ($null -eq $macro -or $macro -ceq '') { continue }
        if ($macro -isnot [System.Collections.IDictionary] -or [string]$macro['macro'] -notmatch '^\{\$[A-Za-z0-9_.]+\}$') { continue }
        if ([string]$macro['type'] -notin @('', '0', 'TEXT') -or [string]$macro['macro'] -match '(?i)SECRET|PASSWORD|PASSWD|COMMUNITY|TOKEN|API.?KEY') { continue }
        $values[[string]$macro['macro']] = [string]$macro['value']
    }
    if ($Overrides) {
        foreach ($key in $Overrides.Keys) {
            if ([string]$key -notmatch '^\{\$[A-Za-z0-9_.]+\}$') { throw "Macro override '$key' must use the complete {`$NAME} form (context macros are not supported)." }
            if ([string]$key -match '(?i)SECRET|PASSWORD|PASSWD|COMMUNITY|TOKEN|API.?KEY') { throw 'Secret-like macro overrides are not accepted by the offline converter.' }
            $values[[string]$key] = [string]$Overrides[$key]
        }
    }
    return ,$values
}

function Expand-ZabbixMacroText {
    param([string]$Text, $Values, [string[]]$Stack = @())
    if ($Stack.Count -gt 32) { throw 'Macro expansion depth exceeds 32.' }
    if ($Text.Length -gt 1048576) { throw 'Macro-expanded value exceeds 1 Mi-character.' }
    $builder = [System.Text.StringBuilder]::new()
    $offset = 0
    foreach ($match in [regex]::Matches($Text, '\{\$[A-Za-z0-9_.]+\}')) {
        [void]$builder.Append($Text.Substring($offset, $match.Index - $offset))
        $key = $match.Value
        if ($Values.ContainsKey($key)) {
            if ($key -cin $Stack) { throw "Macro cycle: $(($Stack + $key) -join ' -> ')." }
            $replacement = Expand-ZabbixMacroText ([string]$Values[$key]) $Values ($Stack + $key)
            [void]$builder.Append($replacement)
        }
        else { [void]$builder.Append($key) }
        if ($builder.Length -gt 1048576) { throw 'Macro-expanded value exceeds 1 Mi-character.' }
        $offset = $match.Index + $match.Length
    }
    [void]$builder.Append($Text.Substring($offset))
    if ($builder.Length -gt 1048576) { throw 'Macro-expanded value exceeds 1 Mi-character.' }
    return $builder.ToString()
}

function Expand-ZabbixTemplateFields {
    param($Value, $Macros, [int]$Depth = 0)
    if ($Depth -gt 64) { throw 'Macro field traversal exceeds depth 64.' }
    if ($Value -is [System.Collections.IDictionary]) {
        $copy = New-ZabbixMap
        foreach ($key in $Value.Keys) {
            if ($key -cin @('name', 'key', 'snmp_oid', 'expression', 'recovery_expression', 'delay', 'units', 'value', 'parameters')) {
                $copy[$key] = Expand-ZabbixTemplateFields $Value[$key] $Macros ($Depth + 1)
            }
            elseif ($Value[$key] -is [array] -or $Value[$key] -is [System.Collections.IDictionary]) {
                # Macro definitions remain unexpanded for provenance/redaction.
                if ($key -ceq 'macros') { $copy[$key] = ConvertTo-ZabbixData $Value[$key] }
                else { $copy[$key] = Expand-ZabbixTemplateFields $Value[$key] $Macros ($Depth + 1) }
            }
            else { $copy[$key] = $Value[$key] }
        }
        return ,$copy
    }
    if ($Value -is [array]) {
        $list = [System.Collections.Generic.List[object]]::new()
        foreach ($item in $Value) { $list.Add((Expand-ZabbixTemplateFields $item $Macros ($Depth + 1))) }
        return ,$list.ToArray()
    }
    if ($Value -is [string]) { return Expand-ZabbixMacroText $Value $Macros }
    return $Value
}


function Test-InterfaceGroupTextMatch {
    [CmdletBinding()]
    param([string]$Text,[Parameter(Mandatory)][string]$Value,
        [ValidateSet('Contains','Substring','StartsWith','EndsWith','Token','Exact')][string]$Match='Contains')
    $textValue=[string]$Text
    switch ($Match) {
        'Exact' { return $textValue.Trim().Equals($Value.Trim(),[StringComparison]::OrdinalIgnoreCase) }
        'StartsWith' { return $textValue.Trim().StartsWith($Value,[StringComparison]::OrdinalIgnoreCase) }
        'EndsWith' { return $textValue.Trim().EndsWith($Value,[StringComparison]::OrdinalIgnoreCase) }
        'Token' { return $textValue -match "(?<![\p{L}\p{N}_])$([regex]::Escape($Value))(?![\p{L}\p{N}_])" }
        default { return $textValue.IndexOf($Value,[StringComparison]::OrdinalIgnoreCase) -ge 0 }
    }
}

function Test-InterfaceGroupRules {
    [CmdletBinding()]
    param([Parameter(Mandatory)][object[]]$Rules)
    if ($Rules.Count -lt 1 -or $Rules.Count -gt 100) { throw 'Provide 1-100 ordered grouping rules.' }
    foreach ($rule in $Rules) {
        $keys=@($rule.PSObject.Properties.Name)
        if ($rule -is [System.Collections.IDictionary]) {$keys=@($rule.Keys)}
        if (@($keys | Where-Object {$_ -notin @('Name','Value','Match','Field')}).Count) {throw 'Rule fields are Name, Value, Match and optional Field only.'}
        if ([string]::IsNullOrWhiteSpace($rule.Name) -or [string]$rule.Name -match '[;\r\n]' -or [string]::IsNullOrWhiteSpace($rule.Value)) {throw 'Each rule needs a nonblank group Name (no semicolons/newlines) and literal Value.'}
        if (([string]$rule.Name).Trim() -ieq 'Other Interfaces') {throw "'Other Interfaces' is reserved for unmatched interfaces."}
        if ($rule.Match -notin @('Contains','StartsWith','EndsWith','Token','Exact')) {throw 'Rule Match must be Contains, StartsWith, EndsWith, Token or Exact.'}
        if ($rule.Field -and $rule.Field -notin @('Any','IfAlias','IfName','IfDescr','InterfaceComment','InterfaceName')) {throw 'Rule Field must be Any or an interface description field.'}
    }
}

function Select-InterfaceGroupRules {
    [CmdletBinding()]
    param([Parameter(Mandatory)][AllowEmptyCollection()][object[]]$Inventory,
        [Parameter(Mandatory)][object[]]$Rules,[ValidateSet('FirstMatch','Overlap')][string]$RuleMode='FirstMatch')
    Test-InterfaceGroupRules -Rules $Rules
    $groups=[ordered]@{}
    foreach ($rule in $Rules) {
        $name=([string]$rule.Name).Trim()
        if ($name -ieq 'Other Interfaces') {throw "'Other Interfaces' is reserved for unmatched interfaces."}
        if (-not $groups.Contains($name)) {$groups[$name]=[System.Collections.Generic.List[object]]::new()}
    }
    $other=[System.Collections.Generic.List[object]]::new()
    foreach ($row in $Inventory) {
        $matched=@{}
        foreach ($rule in $Rules) {
            $fields=@('IfAlias','IfName','IfDescr','InterfaceComment','InterfaceName')
            if ($rule.Field -and $rule.Field -ne 'Any') {$fields=@($rule.Field)}
            $hit=$false
            foreach ($field in $fields) {
                if (Test-InterfaceGroupTextMatch -Text $row.$field -Value $rule.Value -Match $rule.Match) {$hit=$true;break}
            }
            if ($hit) {
                $name=([string]$rule.Name).Trim()
                if (-not $matched.ContainsKey($name)) {$groups[$name].Add($row);$matched[$name]=$true}
                if ($RuleMode -eq 'FirstMatch') {break}
            }
        }
        if (-not $matched.Count) {$other.Add($row)}
    }
    foreach ($name in $groups.Keys) {
        $explanation=@(foreach ($rule in $Rules) {
            if (([string]$rule.Name).Trim() -ieq $name) {
                $field='Any';if ($rule.Field) {$field=$rule.Field}
                "$($rule.Match) '$($rule.Value)' in $field"
            }
        }) -join ' OR '
        [pscustomobject]@{Name=$name;Interfaces=@($groups[$name].ToArray());InterfaceCount=$groups[$name].Count;MatchBasis="Saved ordered rules ($RuleMode): $explanation"}
    }
    [pscustomobject]@{Name='Other Interfaces';Interfaces=@($other.ToArray());InterfaceCount=$other.Count;MatchBasis='No saved rule matched'}
}

function Select-InterfaceGroupSnmpDevice {
    [CmdletBinding()]
    param([Parameter(Mandatory)][int[]]$DeviceId,[ValidateRange(0,10)][int]$ApiMaxRetries=3,[string]$CancellationPath)
    if ($null -eq $PSDefaultParameterValues) {$PSDefaultParameterValues=@{}}
    else {$PSDefaultParameterValues=$PSDefaultParameterValues.Clone()}
    $PSDefaultParameterValues['Get-WUGAPIResponse:MaxRetries']=$ApiMaxRetries
    $ids=@($DeviceId | Select-Object -Unique)
    $selected=[System.Collections.Generic.List[int]]::new()
    $count=0
    try {
        foreach ($id in $ids) {
            Test-InterfaceGroupCancellation -CancellationPath $CancellationPath
            Write-Progress -Id 6202 -Activity 'Checking assigned WUG SNMP credentials' -Status "Device $id" -PercentComplete ([int](100*$count/$ids.Count))
            $credentials=@(Get-WUGDeviceCredential -DeviceId ([string]$id) -Type snmp -View id -ErrorAction Stop)
            if ($credentials.Count) {$selected.Add($id)}
            $count++
        }
    }
    finally {Write-Progress -Id 6202 -Activity 'Checking assigned WUG SNMP credentials' -Completed}
    Write-Verbose "Device eligibility: $($selected.Count) with WUG SNMP credentials; $($ids.Count-$selected.Count) skipped before monitors, traffic and SNMP."
    if (-not $selected.Count) {throw 'No devices in the selected scope have an assigned WUG SNMP credential. No reports or SNMP probes were made.'}
    $selected.ToArray()
}

function Read-InterfaceGroupCollection {
    [CmdletBinding()]
    param([Parameter(Mandatory)][string]$Path)
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "Saved collection not found: $Path. Dashboards generated before collection caching was added do not contain this file. Run Invoke-InterfaceGroupProfile.ps1 -ProfilePath <your-profile.json> -PreviewOnly once to collect and save observations, then replay the returned InventoryPath. Offline replay will not silently query WUG/SNMP or reconstruct observations from incomplete dashboard data."
    }
    $collection=Get-Content -LiteralPath $Path -Raw -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop
    Test-InterfaceGroupCollection -Collection $collection
    $collection
}

function Test-InterfaceGroupCollection {
    [CmdletBinding()]
    param([Parameter(Mandatory)]$Collection)
    if ($collection.SchemaVersion -ne 1 -or -not $collection.PSObject.Properties['Inventory'] -or
        -not $collection.Server -or -not $collection.DeviceIds -or -not $collection.SourceScope -or -not $collection.CollectedUtc -or
        $collection.Range -notin @('lastPolled','today','yesterday','lastWeek','lastNHours','lastNDays') -or $collection.RangeN -lt 1 -or $collection.RangeN -gt 365) {
        throw 'Invalid saved interface collection. Expected a helper-generated collected-inventory.json.'
    }
    $null=[DateTimeOffset]::Parse($collection.CollectedUtc)
    if ($collection.DeviceFilter -notin @('All','SnmpAssigned') -or $collection.CandidateDeviceCount -lt @($collection.DeviceIds).Count -or @($collection.DeviceIds | Where-Object {$_ -le 0}).Count) {
        throw 'Saved collection has invalid device eligibility metadata.'
    }
    $seen=@{}
    foreach ($row in @($collection.Inventory)) {
        $key=Get-InterfaceGroupKey $row
        if ($row.DeviceId -le 0 -or $row.IfIndex -notmatch '^[1-9][0-9]*$' -or $seen.ContainsKey($key) -or $collection.DeviceIds -notcontains $row.DeviceId) {
            throw 'Saved collection has invalid, duplicate or out-of-scope interface identities.'
        }
        $seen[$key]=$true
    }
}

function Export-InterfaceGroupCollection {
    [CmdletBinding(SupportsShouldProcess)]
    param([Parameter(Mandatory)]$Collection,[Parameter(Mandatory)][string]$Path)
    if ($PSCmdlet.ShouldProcess($Path,'Save collected interface observations for offline demo/review')) {
        $full=[IO.Path]::GetFullPath($Path)
        if ([IO.Path]::GetExtension($full) -ine '.json' -or [IO.Path]::GetFileName($full) -in @('groups.json','inventory-snapshot.json','changes.json')) {
            throw 'Use a separate collection JSON filename, not a managed dashboard/baseline file.'
        }
        $current=$full
        while ($current) {
            if (Test-Path -LiteralPath $current) {
                $item=Get-Item -LiteralPath $current -Force -ErrorAction Stop
                if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -or ($current -ne $full -and -not $item.PSIsContainer) -or ($current -eq $full -and $item.PSIsContainer)) {
                    throw 'Collection output requires regular local file/directory paths without reparse points.'
                }
            }
            $parent=Split-Path $current -Parent
            if (-not $parent -or $parent -eq $current) {break}
            $current=$parent
        }
        if (Test-Path -LiteralPath $full) {$null=Read-InterfaceGroupCollection -Path $full}
        $null=New-Item -ItemType Directory -Path (Split-Path $full -Parent) -Force -ErrorAction Stop
        $temporary="$full.$([guid]::NewGuid().ToString('N')).tmp"
        try {
            [IO.File]::WriteAllText($temporary,($Collection | ConvertTo-Json -Depth 20),[Text.UTF8Encoding]::new($true))
            $null=Read-InterfaceGroupCollection -Path $temporary
            Move-Item -LiteralPath $temporary -Destination $full -Force -ErrorAction Stop
        }
        finally {if(Test-Path -LiteralPath $temporary){Remove-Item -LiteralPath $temporary -Force -ErrorAction Stop}}
        $full
    }
}

